package entity;

/**
 * The kinds of items that can be found in the dungeon
 * (the three types listed for Item in our project README).
 */
public enum ItemType {
    /** Used to attack monsters in combat. */
    WEAPON,
    /** Protects the character (armor, shields, rings, etc.). */
    ARMOR,
    /** Consumed for an effect, e.g. healing. */
    POTION
}
