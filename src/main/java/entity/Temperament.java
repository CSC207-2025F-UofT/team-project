package entity;

/**
 * Personality tags a pet profile can carry. Used by the gallery's temperament filter.
 */
public enum Temperament {
    /** Likes cuddles and attention. */
    AFFECTIONATE,
    /** Slow to warm up to new people. */
    SHY,
    /** Enjoys games and toys. */
    PLAYFUL,
    /** Relaxed and quiet. */
    CALM,
    /** Needs lots of exercise. */
    ENERGETIC,
    /** Comfortable around children. */
    GOOD_WITH_KIDS,
    /** Happy to be left alone for a while. */
    INDEPENDENT,
    /** Gets along with other pets in the home. */
    GOOD_WITH_OTHER_PETS
}
