package entity;

/**
 * The main area of the body an {@link Exercise} trains. The list is fixed: it matches the
 * body parts the exercise library offers, so an exercise always falls into exactly one.
 */
public enum BodyPart {
    BACK,
    CARDIO,
    CHEST,
    LOWER_ARMS,
    LOWER_LEGS,
    NECK,
    SHOULDERS,
    UPPER_ARMS,
    UPPER_LEGS,
    WAIST
}
